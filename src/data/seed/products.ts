import type { Product, ProductImage } from "@/domain/types";
import { mediaUrl } from "@/lib/media-url";

const now = "2026-09-22T00:00:00.000Z";

function img(id: string, url: string, sortOrder = 0, isPrimary = true): ProductImage {
  return { id, url, sortOrder, isPrimary, alt: "" };
}

type SeedInput = {
  id: string;
  name: string;
  slug: string;
  sku: string;
  categoryId: string;
  shortDescription: string;
  description: string;
  price: number;
  salePrice?: number | null;
  compareAtPrice?: number | null;
  stockQuantity: number;
  featured?: boolean;
  bestSeller?: boolean;
  newArrival?: boolean;
  saleBadge?: boolean;
  images: ProductImage[];
  features: string[];
  tags: string[];
  specifications?: Record<string, string>;
  published?: boolean;
};

function build(p: SeedInput): Product {
  return {
    id: p.id,
    name: p.name,
    slug: p.slug,
    sku: p.sku,
    categoryId: p.categoryId,
    shortDescription: p.shortDescription,
    description: p.description,
    price: p.price,
    salePrice: p.salePrice ?? null,
    compareAtPrice: p.compareAtPrice ?? null,
    stockQuantity: p.stockQuantity,
    stockStatus: p.stockQuantity > 0 ? "in_stock" : "out_of_stock",
    featured: p.featured ?? false,
    bestSeller: p.bestSeller ?? false,
    newArrival: p.newArrival ?? false,
    saleBadge: p.saleBadge ?? Boolean(p.salePrice),
    manualBadges: [],
    images: p.images,
    specifications: p.specifications ?? {
      Warranty: "6 months",
      Origin: "Imported",
    },
    features: p.features,
    tags: p.tags,
    seoTitle: `${p.name} | HANIA Electronics`,
    seoDescription: p.shortDescription,
    published: p.published ?? true,
    createdAt: now,
    updatedAt: now,
  };
}

